"""Projects, members, stakeholders and allocations on the 37-table schema.

API shape is camelCase with ISO date strings. Mapping:
* ``projects.name / start_date / planned_end_date / actual_end_date / end_customer_name``; ``project_number``
  (PRJ1001...) is generated by the database trigger and is never sent.
* ``project_members`` (PROJECT_MANAGER / ACCOUNT_OWNER employees) <-> projectManagerIds / accountOwnerIds
* ``project_stakeholders`` (free-text client contacts, not linked to employees) <-> clientStakeholders
* ``allocations.is_billable / billable_percentage``; work place is at most one of client_location_id (UUID),
  work_office_location_id (workLocationKind OFFICE) or work_address_id (RESIDENTIAL)
Every change is also written to ``activity_log``.
"""
