async def _project_payload(db: AsyncSession, project: Project) -> dict:
    return (await _project_payloads(db, [project]))[0]


async def _project_payloads(db: AsyncSession, projects: list[Project]) -> list[dict]:
    project_ids = [p.id for p in projects]
    stakeholders = await _load_stakeholders_many(db, project_ids)
    client_stakeholders = await _load_client_stakeholders_many(db, project_ids)
    allocations = await _load_allocations_many(db, project_ids)
    client_ids = {p.client_id for p in projects if p.client_id is not None}
    customers: dict[uuid.UUID, Client] = {}
    if client_ids:
        cust = await db.execute(select(Client).where(Client.id.in_(client_ids)))
        customers = {c.id: c for c in cust.scalars().all()}
    payloads: list[dict] = []
    for project in projects:
        managers, owners = stakeholders[project.id]
        customer = customers.get(project.client_id) if project.client_id else None
        base = project_to_dict(project)
        base.update(
            {
                "clientName": customer.client_name if customer is not None else None,
                "isInternalClient": (
                    (customer.client_category or "").upper() == "INTERNAL" if customer is not None else None
                ),
                "clientCategory": (
                    client_category_to_api(customer.client_category) if customer is not None else None
                ),
                "projectManagers": managers,
                "accountOwners": owners,
                "projectManagerIds": [m["employeeId"] for m in managers],
                "accountOwnerIds": [o["employeeId"] for o in owners],
                "clientStakeholders": client_stakeholders[project.id],
                "allocations": allocations[project.id],
            }
        )
        payloads.append(base)
    return payloads


async def _load_client_stakeholders_many(
    db: AsyncSession, project_ids: list[uuid.UUID]
) -> dict[uuid.UUID, list[dict[str, Any]]]:
    grouped: dict[uuid.UUID, list[dict[str, Any]]] = {pid: [] for pid in project_ids}
