async def _load_stakeholders(
    db: AsyncSession, project_id: uuid.UUID
) -> tuple[list[dict], list[dict]]:
    return (await _load_stakeholders_many(db, [project_id]))[project_id]


async def _load_stakeholders_many(
    db: AsyncSession, project_ids: list[uuid.UUID]
) -> dict[uuid.UUID, tuple[list[dict], list[dict]]]:
    """Managers and account owners for many projects in one joined query."""
    grouped: dict[uuid.UUID, tuple[list[dict], list[dict]]] = {pid: ([], []) for pid in project_ids}
    if not project_ids:
        return grouped
    result = await db.execute(
        select(ProjectMember, Employee)
        .join(Employee, Employee.id == ProjectMember.employee_id)
        .where(ProjectMember.project_id.in_(project_ids))
    )
    for member, employee in result.all():
        managers, owners = grouped[member.project_id]
        display = f"{employee.first_name or ''} {employee.last_name or ''}".strip() or (
            employee.official_email or str(employee.id)
        )
        row = {"employeeId": str(employee.id), "displayName": display, "role": member.role}
        if member.role == "PROJECT_MANAGER":
            managers.append(row)
        elif member.role == "ACCOUNT_OWNER":
            owners.append(row)
    return grouped


def _employee_personal_address_fields(address: Address | None = None) -> tuple[str | None, str | None]:
    address_id = str(address.id) if address is not None and address.id else None
    return address_id, personal_address_label(address)


async def _personal_addresses_by_employee(
    db: AsyncSession, employee_ids: list[uuid.UUID]
) -> dict[uuid.UUID, Address | None]:
    if not employee_ids:
        return {}
    unique_ids = list(dict.fromkeys(employee_ids))
    result = await db.execute(select(Address).where(Address.employee_id.in_(unique_ids)))
    grouped: dict[uuid.UUID, list[Address]] = {}
    for addr in result.scalars().all():
        grouped.setdefault(addr.employee_id, []).append(addr)
    return {eid: preferred_personal_address(grouped.get(eid, [])) for eid in unique_ids}


async def _office_locations_by_id(
    db: AsyncSession, location_ids: list[uuid.UUID]
) -> dict[uuid.UUID, Location]:
    if not location_ids:
        return {}
    unique_ids = list(dict.fromkeys(location_ids))
    result = await db.execute(select(Location).where(Location.id.in_(unique_ids)))
    return {row.id: row for row in result.scalars().all()}


def _client_location_label(row: ClientLocation | None) -> str | None:
    if row is None:
        return None
    name = str(row.location_name or "").strip()
    if name:
        return name
    parts = [
        str(part or "").strip() for part in (row.city, row.state_province, row.country) if str(part or "").strip()
    ]
    if parts:
        return ", ".join(parts)
    return str(row.address_line_1 or "").strip() or None


async def _client_locations_by_id(
    db: AsyncSession, ids: list[uuid.UUID]
) -> dict[uuid.UUID, ClientLocation]:
    if not ids:
        return {}
    result = await db.execute(select(ClientLocation).where(ClientLocation.id.in_(list(dict.fromkeys(ids)))))
    return {row.id: row for row in result.scalars().all()}


def _work_location_fields(
    allocation: Allocation,
    *,
    office: Location | None,
    personal: Address | None,
) -> tuple[str | None, str | None, str | None]:
    if allocation.work_office_location_id is not None:
        label = None
        if office is not None and office.id == allocation.work_office_location_id:
            label = location_address_label(office) or (str(office.name or "").strip() or None)
        return str(allocation.work_office_location_id), "OFFICE", label
    if allocation.work_address_id is not None:
        label = personal_address_label(personal) if personal is not None else None
        return str(allocation.work_address_id), "RESIDENTIAL", label
    return None, None, None


async def _allocation_payload(
    allocation: Allocation,
    employee: Employee,
    designation_title: str | None,
    *,
    address: Address | None = None,
    office: Location | None = None,
    client_location: ClientLocation | None = None,
) -> dict:
    display = f"{employee.first_name or ''} {employee.last_name or ''}".strip() or (
        employee.official_email or str(employee.id)
    )
    designation = (
        (designation_title or "").strip() or (employee.role or "").strip()
        or (employee.department_label or "").strip() or "—"
    )
    work_id, work_kind, work_label = _work_location_fields(allocation, office=office, personal=address)
    return {
        "allocationId": str(allocation.id),
        "employeeId": str(allocation.employee_id),
        "employeeName": display,
        "employeeCode": employee.employee_code or employee.emp_id or "",
        "designation": designation,
        "projectId": str(allocation.project_id),
        "roleOnProject": allocation.role_on_project,
        "allocationPercentage": float(allocation.allocation_percentage),
        "startDate": _iso(allocation.start_date),
        "endDate": _iso(allocation.end_date),
        "billable": bool(allocation.is_billable),
        "billabilityPercentage": (
            float(allocation.billable_percentage) if allocation.billable_percentage is not None else None
        ),
        "clientLocationId": str(allocation.client_location_id) if allocation.client_location_id else None,
        "clientLocationLabel": _client_location_label(client_location),
        "workLocationId": work_id,
        "workLocationKind": work_kind,
        "workLocationLabel": work_label,
    }


async def _load_allocations(db: AsyncSession, project_id: uuid.UUID) -> list[dict]:
    return (await _load_allocations_many(db, [project_id]))[project_id]


async def _load_allocations_many(
    db: AsyncSession, project_ids: list[uuid.UUID]
) -> dict[uuid.UUID, list[dict]]:
    grouped: dict[uuid.UUID, list[dict]] = {pid: [] for pid in project_ids}
    if not project_ids:
        return grouped
    result = await db.execute(
        select(Allocation, Employee, Designation)
        .join(Employee, Employee.id == Allocation.employee_id)
        .outerjoin(Designation, Designation.id == Employee.designation_id)
        .where(Allocation.project_id.in_(project_ids))
        .order_by(Allocation.start_date.asc(), Allocation.id.asc())
    )
    matched = result.all()
    addresses = await _personal_addresses_by_employee(db, [emp.id for _, emp, _ in matched])
    office_ids = [a.work_office_location_id for a, _, _ in matched if a.work_office_location_id is not None]
    offices = await _office_locations_by_id(db, office_ids)
    client_locations = await _client_locations_by_id(
        db, [a.client_location_id for a, _, _ in matched if a.client_location_id is not None]
    )
    for allocation, employee, designation in matched:
        grouped[allocation.project_id].append(
            await _allocation_payload(
                allocation,
                employee,
                designation.name if designation is not None else None,
                address=addresses.get(employee.id),
                office=offices.get(allocation.work_office_location_id),
                client_location=client_locations.get(allocation.client_location_id),
            )
        )
    return grouped


async def _get_project_or_404(db: AsyncSession, project_id: uuid.UUID) -> Project:
    project = (await db.execute(select(Project).where(Project.id == project_id))).scalar_one_or_none()
    if project is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Project not found")
    return project


def _project_effective_end(project: Project) -> date | None:
    return project.actual_end_date or project.planned_end_date


def _assert_project_open_for_allocation(project: Project) -> None:
    project_end = _project_effective_end(project)
    today = datetime.utcnow().date()
    if not project_end or project_end >= today:
        return
    if project.actual_end_date:
        detail = (
            f"This project ended on {project_end.isoformat()} (actual end date). "
            "Update the Actual End Date to allocate resources."
        )
    else:
        detail = (
            f"This project's end date ({project_end.isoformat()}) has passed. "
            "Set an Actual End Date to allocate resources."
        )
    raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=detail)


def _assert_allocation_dates_within_project(
    project: Project, *, start_date: date, end_date: date | None
) -> None:
    project_start = project.start_date
    project_end = _project_effective_end(project)
    if project_start and start_date < project_start:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Allocation startDate cannot be before the project start date",
        )
    if project_end and start_date > project_end:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Allocation startDate cannot be after the project end date",
        )
    if end_date:
        if project_start and end_date < project_start:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Allocation endDate cannot be before the project start date",
            )
        if project_end and end_date > project_end:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Allocation endDate cannot be after the project end date",
            )


def _validation_detail(exc: ValidationError) -> str:
    return "; ".join(f"{'.'.join(str(p) for p in err['loc'])}: {err['msg']}" for err in exc.errors())


def _parse_allocation_batch(payload: dict[str, Any]) -> AllocationBatchBody:
    try:
        return AllocationBatchBody.model_validate(payload)
    except ValidationError as exc:
        detail = _validation_detail(exc)
        logger.warning("allocation batch rejected: %s", detail)
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=detail) from exc


def _existing_row_to_update(
    item: AllocationWriteBody, existing_by_id: dict[uuid.UUID, Allocation]
) -> Allocation | None:
    if item.allocation_id is None:
        return None
    row = existing_by_id.get(item.allocation_id)
    if row is None or row.employee_id != item.employee_id:
        return None
    return row


