def project_meta() -> dict[str, Any]:
    """Return master lists used by project create/edit dropdowns."""
    return {
        "projectTypes": list(PROJECT_TYPES),
        "billingTypes": list(BILLING_TYPES),
        "statuses": [
            {"value": value, "label": PROJECT_STATUS_LABELS[value]} for value in PROJECT_STATUSES
        ],
    }


def _normalize_status(raw: str | None, *, default: str = "ACTIVE") -> str:
    if not raw:
        return default
    value = str(raw).strip().upper().replace(" ", "_")
    if value in {"INACTIVE", "CLOSED"}:
        return "CLOSED"
    if value in {"ONHOLD", "ON_HOLD"}:
        return "ON_HOLD"
    if value == "ACTIVE":
        return "ACTIVE"
    return default


def _parse_date(value: Any, field: str) -> date | None:
    if value in (None, ""):
        return None
    if isinstance(value, date):
        return value
    try:
        return date.fromisoformat(str(value).strip()[:10])
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail=f"{field} must be a valid date (YYYY-MM-DD)"
        ) from exc


def _iso(value: date | None) -> str | None:
    return value.isoformat() if value else None


def _db_error_to_http(exc: DBAPIError) -> HTTPException:
    message = str(getattr(exc, "orig", exc))
    if "uq_projects_project_code" in message:
        return HTTPException(status_code=400, detail="A project with this code already exists")
    if "ck_projects_planned_end" in message or "ck_projects_actual_end" in message:
        return HTTPException(status_code=400, detail="End date cannot be before the start date")
    if "uq_project_members_project_employee_role" in message:
        return HTTPException(status_code=400, detail="That employee already has this role on the project")
    detail = message.splitlines()[0] if message else "Database rejected the change"
    # asyncpg prefixes the exception class: "<class 'asyncpg.exceptions.CheckViolationError'>: msg"
    if ">: " in detail:
        detail = detail.split(">: ", 1)[1]
    return HTTPException(status_code=400, detail=detail)


def _actor_id(actor: dict | None) -> uuid.UUID | None:
    raw = (actor or {}).get("employeeId") or (actor or {}).get("id")
    try:
        return uuid.UUID(str(raw)) if raw else None
    except ValueError:
        return None


def _log_value(value: Any) -> Any:
    if isinstance(value, (uuid.UUID, date, Decimal)):
        return value.isoformat() if isinstance(value, date) else str(value)
    return value


def _snapshot(row: Any, fields: tuple[str, ...]) -> dict[str, Any]:
    return {field: _log_value(getattr(row, field, None)) for field in fields}


def _changed(before: dict[str, Any], after: dict[str, Any]) -> dict[str, Any]:
    return {k: {"old": before.get(k), "new": v} for k, v in after.items() if before.get(k) != v}


