def _end_customer(customer: Client | None, body_value: str | None) -> str | None:
    """End customer is only for an Intermediary client; a value for any other client is refused."""
    if customer is None or (customer.client_category or "").upper() != "INTERMEDIARY":
        if body_value:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Only a project of an Intermediary client can have an end customer name",
            )
        return None
    return body_value


async def create_project(db: AsyncSession, actor: dict, payload: dict[str, Any]) -> dict:
    if payload.get("projectNumber") or payload.get("project_number") or payload.get("projectDisplayId"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="projectNumber is generated by the database and must not be supplied",
        )
    body = _parse_body(payload)
    name = (body.project_name or "").strip()
    if not name:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Project name is required")
    if len(name) > 100:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="Project name must be at most 100 characters"
        )
    if body.client_id is None:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Client is required")
    customer = await _ensure_customer(db, body.client_id)
    is_internal = (customer.client_category or "").upper() == "INTERNAL"
    billing_type = None if is_internal else body.billing_type
    if not is_internal and billing_type is not None and billing_type not in BILLING_TYPES:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid billing type")
    start = _parse_date(body.project_startdate, "projectStartdate")
    if start is None:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Project start date is required")

    await _assert_unique_name(db, name)
    await _assert_unique_code(db, body.project_code)

    project = Project(
        id=uuid.uuid4(),
        name=name,
        start_date=start,
        planned_end_date=_parse_date(body.resolved_planned_end(), "plannedEndDate"),
        actual_end_date=_parse_date(body.actual_end_date, "actualEndDate"),
        status=_normalize_status(body.status, default="ACTIVE"),
        client_id=body.client_id,
        project_code=body.project_code,
        project_type=body.project_type,
        region=body.region,
        billing_type=billing_type,
        end_customer_name=_end_customer(customer, body.end_client_name),
        description=body.description,
    )
    db.add(project)
    try:
        await db.flush()
        await db.refresh(project)  # project_number comes from the trigger
        await write_log(
            db, action="created", entity_type="project", entity_id=project.id,
            actor_employee_id=_actor_id(actor), details=_snapshot(project, _PROJECT_LOG_FIELDS),
        )
        await _replace_stakeholders(db, actor, project.id, body.project_manager_ids, body.account_owner_ids)
        await _replace_client_stakeholders(db, actor, project.id, body.client_stakeholders)
        await db.flush()
    except DBAPIError as exc:
        raise _db_error_to_http(exc) from exc
    return await _project_payload(db, project)


async def update_project(
    db: AsyncSession, actor: dict, project_id: uuid.UUID, payload: dict[str, Any]
) -> dict:
    project = await _get_project_or_404(db, project_id)
    if payload.get("projectNumber") or payload.get("project_number"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="projectNumber cannot be changed"
        )
    body = _parse_body(payload)
    before = _snapshot(project, _PROJECT_LOG_FIELDS)
    try:
        if body.project_name is not None:
            name = body.project_name.strip()
            if not name:
                raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Project name is required")
            if len(name) > 100:
                raise HTTPException(
                    status_code=status.HTTP_400_BAD_REQUEST,
                    detail="Project name must be at most 100 characters",
                )
            await _assert_unique_name(db, name, exclude_id=project_id)
            project.name = name
        customer: Client | None = None
        client_changed = body.client_id is not None and body.client_id != project.client_id
        if body.client_id is not None:
            customer = (
                await _ensure_customer(db, body.client_id)
                if client_changed
                else (await db.execute(select(Client).where(Client.id == body.client_id))).scalar_one_or_none()
            )
            project.client_id = body.client_id
        if "projectStartdate" in payload and body.project_startdate:
            project.start_date = _parse_date(body.project_startdate, "projectStartdate")
        if "plannedEndDate" in payload or "projectEnddate" in payload:
            project.planned_end_date = _parse_date(body.resolved_planned_end(), "plannedEndDate")
        if "actualEndDate" in payload:
            project.actual_end_date = _parse_date(body.actual_end_date, "actualEndDate")
        if body.status is not None:
            project.status = _normalize_status(body.status)
        if "projectCode" in payload:
            await _assert_unique_code(db, body.project_code, exclude_id=project_id)
            project.project_code = body.project_code
        if "projectType" in payload:
            project.project_type = body.project_type
        if "region" in payload:
            project.region = body.region
        if customer is None and project.client_id is not None:
            customer = (
                await db.execute(select(Client).where(Client.id == project.client_id))
            ).scalar_one_or_none()
        if customer is not None and (customer.client_category or "").upper() == "INTERNAL":
            project.billing_type = None
        elif body.billing_type is not None:
            project.billing_type = body.billing_type
        if body.end_client_name is not None or "endClientName" in payload:
            project.end_customer_name = _end_customer(customer, body.end_client_name)
        elif client_changed and (customer is None or (customer.client_category or "").upper() != "INTERMEDIARY"):
            project.end_customer_name = None
        if "description" in payload:
            project.description = body.description
        await db.flush()
        diff = _changed(before, _snapshot(project, _PROJECT_LOG_FIELDS))
        if diff:
            await write_log(
                db, action="updated", entity_type="project", entity_id=project.id,
                actor_employee_id=_actor_id(actor), details=diff,
            )

        if "projectManagerIds" in payload or "accountOwnerIds" in payload:
            existing_managers, existing_owners = await _load_stakeholders(db, project_id)
            managers = (
                body.project_manager_ids
                if "projectManagerIds" in payload
                else [uuid.UUID(m["employeeId"]) for m in existing_managers]
            )
            owners = (
                body.account_owner_ids
                if "accountOwnerIds" in payload
                else [uuid.UUID(o["employeeId"]) for o in existing_owners]
            )
            await _replace_stakeholders(db, actor, project_id, managers, owners)
        if "clientStakeholders" in payload:
            await _replace_client_stakeholders(db, actor, project_id, body.client_stakeholders)
        await db.flush()
    except DBAPIError as exc:
        raise _db_error_to_http(exc) from exc
    return await _project_payload(db, project)


async def set_project_members(
    db: AsyncSession, actor: dict, project_id: uuid.UUID, payload: dict[str, Any]
) -> dict:
    """PUT /projects/{id}/members: replace project managers and/or account owners."""
    await _get_project_or_404(db, project_id)
    body = _parse_body({k: payload[k] for k in ("projectManagerIds", "accountOwnerIds") if k in payload})
    existing_managers, existing_owners = await _load_stakeholders(db, project_id)
    managers = (
        body.project_manager_ids
        if "projectManagerIds" in payload
        else [uuid.UUID(m["employeeId"]) for m in existing_managers]
    )
    owners = (
        body.account_owner_ids
        if "accountOwnerIds" in payload
        else [uuid.UUID(o["employeeId"]) for o in existing_owners]
    )
    try:
        await _replace_stakeholders(db, actor, project_id, managers, owners)
        await db.flush()
    except DBAPIError as exc:
        raise _db_error_to_http(exc) from exc
    return await get_project(db, project_id)


