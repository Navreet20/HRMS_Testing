async def list_active_allocations(
    db: AsyncSession, employee_ids: list[uuid.UUID] | None = None
) -> list[dict]:
    """Allocations still running (no end date, or ending today or later), without names."""
    today = date.today()
    stmt = select(
        Allocation.id,
        Allocation.employee_id,
        Allocation.project_id,
        Allocation.allocation_percentage,
        Allocation.start_date,
        Allocation.end_date,
    ).where((Allocation.end_date.is_(None)) | (Allocation.end_date >= today))
    if employee_ids:
        stmt = stmt.where(Allocation.employee_id.in_(employee_ids))
    result = await db.execute(stmt)
    return [
        {
            "allocationId": str(allocation_id),
            "employeeId": str(employee_id),
            "projectId": str(project_id),
            "allocationPercentage": float(percentage),
            "startDate": _iso(start_date),
            "endDate": _iso(end_date),
        }
        for allocation_id, employee_id, project_id, percentage, start_date, end_date in result.all()
    ]


