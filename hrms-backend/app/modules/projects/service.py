def _uuid_or_none(raw: str | None, field: str) -> uuid.UUID | None:
    if not raw:
        return None
    try:
        return uuid.UUID(str(raw))
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=f"Invalid {field}") from exc


def _work_place_columns(item: AllocationWriteBody) -> dict[str, uuid.UUID | None]:
    client_location_id = _uuid_or_none(item.client_location_id, "clientLocationId")
    work_id = _uuid_or_none(item.work_location_id, "workLocationId")
    kind = (item.work_location_kind or "").upper() or None
    cols: dict[str, uuid.UUID | None] = {
        "client_location_id": None,
        "work_office_location_id": None,
        "work_address_id": None,
    }
    # The schema allows only one place per allocation: client site wins, then the explicit work place.
    if client_location_id is not None:
        cols["client_location_id"] = client_location_id
    elif work_id is not None and kind == "RESIDENTIAL":
        cols["work_address_id"] = work_id
    elif work_id is not None:
        cols["work_office_location_id"] = work_id
    return cols


async def sync_allocations(
    db: AsyncSession, actor: dict, project_id: uuid.UUID, payload: dict[str, Any]
) -> list[dict]:
    """Replace project allocations with the provided list (create/update; soft-end removed)."""
    project = await _get_project_or_404(db, project_id)
    if _normalize_status(project.status, default="ACTIVE") in CLOSED_STATUSES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="Cannot allocate resources to a closed project"
        )
    _assert_project_open_for_allocation(project)

    body = _parse_allocation_batch(payload)
    items = body.allocations

    seen_employees: set[uuid.UUID] = set()
    for item in items:
        if item.employee_id in seen_employees:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Each employee can only appear once in the allocation list",
            )
        seen_employees.add(item.employee_id)

    parsed_dates: list[tuple[date, date | None]] = []
    for item in items:
        start = _parse_date(item.start_date, "startDate")
        end = _parse_date(item.end_date, "endDate")
        assert start is not None
        _assert_allocation_dates_within_project(project, start_date=start, end_date=end)
        parsed_dates.append((start, end))
    await _validate_active_employees(db, [item.employee_id for item in items])

    existing_result = await db.execute(select(Allocation).where(Allocation.project_id == project_id))
    existing_by_id = {row.id: row for row in existing_result.scalars().all()}
    keep_ids: set[uuid.UUID] = set()

    try:
        for item, (start, end) in zip(items, parsed_dates):
            places = _work_place_columns(item)
            row = _existing_row_to_update(item, existing_by_id)
            if row is not None:
                before = _snapshot(row, _ALLOCATION_LOG_FIELDS)
                row.role_on_project = item.role_on_project
                row.allocation_percentage = _dec(item.allocation_percentage)
                row.start_date = start
                row.end_date = end
                row.is_billable = bool(item.billable)
                row.billable_percentage = _dec(item.billability_percentage)
                for key, value in places.items():
                    setattr(row, key, value)
                await db.flush()
                await db.refresh(row)
                diff = _changed(before, _snapshot(row, _ALLOCATION_LOG_FIELDS))
                if diff:
                    await write_log(
                        db, action="updated", entity_type="allocation", entity_id=row.id,
                        actor_employee_id=_actor_id(actor), details=diff,
                    )
                keep_ids.add(row.id)
            else:
                row = Allocation(
                    id=uuid.uuid4(),
                    employee_id=item.employee_id,
                    project_id=project_id,
                    role_on_project=item.role_on_project,
                    allocation_percentage=_dec(item.allocation_percentage),
                    start_date=start,
                    end_date=end,
                    is_billable=bool(item.billable),
                    billable_percentage=_dec(item.billability_percentage),
                    **places,
                )
                db.add(row)
                await db.flush()
                await write_log(
                    db, action="created", entity_type="allocation", entity_id=row.id,
                    actor_employee_id=_actor_id(actor), details=_snapshot(row, _ALLOCATION_LOG_FIELDS),
                )
                keep_ids.add(row.id)

        today = datetime.utcnow().date()
        for allocation_id, row in existing_by_id.items():
            if allocation_id in keep_ids:
                continue
            if row.start_date > today:
                snap = _snapshot(row, _ALLOCATION_LOG_FIELDS)
                await db.delete(row)
                await db.flush()
                await write_log(
                    db, action="deleted", entity_type="allocation", entity_id=allocation_id,
                    actor_employee_id=_actor_id(actor), details=snap,
                )
                continue
            end_date = max(today - timedelta(days=1), row.start_date)
            if not row.end_date or row.end_date > end_date:
                old_end = row.end_date
                row.end_date = end_date
                await db.flush()
                await write_log(
                    db, action="updated", entity_type="allocation", entity_id=allocation_id,
                    actor_employee_id=_actor_id(actor),
                    details={"end_date": {"old": _log_value(old_end), "new": end_date.isoformat()}},
                )
        await db.flush()
    except DBAPIError as exc:
        raise _db_error_to_http(exc) from exc
    return await _load_allocations(db, project_id)


async def end_allocation(
    db: AsyncSession,
    actor: dict,
    project_id: uuid.UUID,
    allocation_id: uuid.UUID,
    payload: dict[str, Any],
) -> dict:
    project = await _get_project_or_404(db, project_id)
    try:
        body = AllocationEndBody.model_validate(payload)
    except ValidationError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=_validation_detail(exc)) from exc

    matched = (
        await db.execute(
            select(Allocation, Employee, Designation)
            .join(Employee, Employee.id == Allocation.employee_id)
            .outerjoin(Designation, Designation.id == Employee.designation_id)
            .where(Allocation.id == allocation_id, Allocation.project_id == project_id)
        )
    ).first()
    if matched is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Allocation not found")
    allocation, employee, designation = matched
    end = _parse_date(body.end_date, "endDate")
    assert end is not None
    if end < allocation.start_date:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="endDate must be on or after startDate"
        )
    _assert_allocation_dates_within_project(project, start_date=allocation.start_date, end_date=end)
    old_end = allocation.end_date
    allocation.end_date = end
    try:
        await db.flush()
    except DBAPIError as exc:
        raise _db_error_to_http(exc) from exc
    await write_log(
        db, action="updated", entity_type="allocation", entity_id=allocation.id,
        actor_employee_id=_actor_id(actor),
        details={"end_date": {"old": _log_value(old_end), "new": end.isoformat()}},
    )
    addresses = await _personal_addresses_by_employee(db, [employee.id])
    offices = await _office_locations_by_id(
        db, [allocation.work_office_location_id] if allocation.work_office_location_id else []
    )
    client_locations = await _client_locations_by_id(
        db, [allocation.client_location_id] if allocation.client_location_id else []
    )
    return await _allocation_payload(
        allocation,
        employee,
        designation.name if designation is not None else None,
        address=addresses.get(employee.id),
        office=offices.get(allocation.work_office_location_id),
        client_location=client_locations.get(allocation.client_location_id),
    )
