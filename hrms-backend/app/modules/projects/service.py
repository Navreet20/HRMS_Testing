async def delete_project(db: AsyncSession, project_id: uuid.UUID, actor: dict | None = None) -> dict:
    """A project is never deleted: it is closed."""
    project = await _get_project_or_404(db, project_id)
    if project.status != "CLOSED":
        old = project.status
        project.status = "CLOSED"
        await db.flush()
        await write_log(
            db, action="deactivated", entity_type="project", entity_id=project.id,
            actor_employee_id=_actor_id(actor), details={"status": {"old": old, "new": "CLOSED"}},
        )
    return await _project_payload(db, project)


