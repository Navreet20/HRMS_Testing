def lookup_country_code(value: str | None) -> str | None:
    """Return ISO alpha-2 or None. Does not raise (safe for legacy GET rows)."""
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    upper = text.upper()
    if len(upper) == 2 and upper.isalpha() and upper in ISO_COUNTRY_CODES:
        return upper
    return _COUNTRY_NAME_TO_CODE.get(text.casefold())


def subdivisions_for(country_code: str) -> dict[str, str] | None:
    """Subdivision code → name, or None when the country has no static list."""
    table = _SUBDIVISIONS.get(country_code)
    return dict(table) if table else None


def lookup_state_code(country_code: str, value: str) -> str | None:
    """Normalize a state/region to its code when we have a list; else None."""
    table = _SUBDIVISIONS.get(country_code)
    if not table:
        return None
    text = value.strip()
    if not text:
        return None
    upper = text.upper()
    if upper in table:
        return upper
    folded = text.casefold()
    for code, name in table.items():
        if name.casefold() == folded:
            return code
    return _SUBDIVISION_ALIASES.get(country_code, {}).get(folded)


CITY_OPTIONAL_COUNTRY_CODES = frozenset({"MC", "SG", "SM", "VA"})


def city_is_required(country_code: str | None) -> bool:
    """City-states / microstates can be saved without a city value."""
    code = lookup_country_code(country_code) if country_code else None
    if code is None:
        return True
    return code not in CITY_OPTIONAL_COUNTRY_CODES
