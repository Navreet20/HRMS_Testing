"""Clients on the 37-table schema (``clients`` and ``client_locations``).

The API keeps the camelCase shape. Mapping: ``clients.status`` ACTIVE / INACTIVE (the old "Archived" is still
accepted on input), ``clients.client_category`` INTERNAL/DIRECT/INTERMEDIARY <-> API internal/direct/intermediary,
``clients.account_owner`` (employee id, REQUIRED) <-> accountOwnerId. ``client_code`` (CLI1001...) is generated by
the database trigger and is never sent. Contacts live on projects (``project_stakeholders``), not on the client, and
client invoices have no table yet (reads return empty, writes answer 501).
"""
