def _text(value: Any) -> str:
    return str(value or "").strip()


def _optional_text(value: Any) -> str | None:
    text = _text(value)
    return text or None


def _bool(value: Any, default: bool = False) -> bool:
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    text = str(value).strip().lower()
    if text in {"true", "1", "yes"}:
        return True
    if text in {"false", "0", "no"}:
        return False
    return default


def _parse_client_category(payload: dict[str, Any], *, required: bool) -> str | None:
    """Category from ``clientCategory``; legacy ``isInternal: true`` maps to internal."""
    raw = payload.get("clientCategory")
    if raw is None:
        raw = payload.get("client_category")
    category = _text(raw).lower()
    if category:
        if category not in CLIENT_CATEGORIES:
            raise HTTPException(status_code=400, detail=CLIENT_CATEGORY_INVALID)
        return category
    if _bool(payload.get("isInternal") or payload.get("is_internal"), False):
        return CLIENT_CATEGORY_INTERNAL
    if required:
        raise HTTPException(status_code=400, detail=CLIENT_CATEGORY_REQUIRED)
    return None


def parse_client_create_payload(payload: dict[str, Any]) -> dict[str, Any]:
    name = _text(payload.get("clientName") or payload.get("customerName") or payload.get("name"))
    if not name:
        raise HTTPException(status_code=400, detail="Client name is required.")
    if len(name) > 100:
        raise HTTPException(status_code=400, detail="Client name must be 100 characters or fewer.")
    industry = _text(
        payload.get("industry")
        or payload.get("clientType")
        or payload.get("customerType")
        or payload.get("type")
    )
    if not industry:
        raise HTTPException(status_code=400, detail="Industry is required.")
    client_category = _parse_client_category(payload, required=True)
    is_internal = client_category == CLIENT_CATEGORY_INTERNAL
    parsed_locations = _parse_client_locations(payload.get("locations"), allow_empty=True)
    return {
        "name": name,
        "industry": industry,
        "accountOwnerId": payload.get("accountOwnerId") or payload.get("account_owner_id"),
        "isInternal": is_internal,
        "clientCategory": client_category,
        "locations": parsed_locations,
    }


def _parse_org_location_id(raw: Any) -> uuid.UUID | None:
    if raw in (None, ""):
        return None
    try:
        return uuid.UUID(str(raw))
    except (TypeError, ValueError) as exc:
        raise HTTPException(status_code=400, detail="Invalid locationId") from exc


def _parse_client_locations(raw: Any, *, allow_empty: bool = False) -> list[dict[str, Any]]:
    if not isinstance(raw, list) or not raw:
        if allow_empty:
            return []
        raise HTTPException(status_code=400, detail="Add at least one operating location.")
    parsed: list[dict[str, Any]] = []
    for row in raw:
        if not isinstance(row, dict):
            raise HTTPException(status_code=400, detail="Each location must be an object.")
        org_location_id = _parse_org_location_id(
            row.get("locationId") or row.get("orgLocationId") or row.get("officeLocationId")
        )
        country = _text(row.get("country"))
        if not country and org_location_id is None:
            raise HTTPException(status_code=400, detail="Country is required.")
        location_name = _optional_text(row.get("locationName"))
        if location_name and len(location_name) > LOCATION_NAME_MAX:
            raise HTTPException(
                status_code=400, detail=f"Location name must be {LOCATION_NAME_MAX} characters or fewer."
            )
        address = _optional_text(row.get("address") or row.get("addressLine1"))
        if address and len(address) > LOCATION_ADDRESS_MAX:
            raise HTTPException(
                status_code=400, detail=f"Address must be {LOCATION_ADDRESS_MAX} characters or fewer."
            )
        parsed.append(
            {
                "id": row.get("id"),
                "clientLocationId": row.get("clientLocationId"),
                "locationId": org_location_id,
                "locationName": location_name,
                "country": country,
                "stateProvince": _optional_text(row.get("stateProvince") or row.get("state")),
                "city": _optional_text(row.get("city")),
                "address": address,
                "addressLine2": _optional_text(row.get("addressLine2")),
                "zip": _optional_text(row.get("zip") or row.get("zipCode") or row.get("postalCode")),
            }
        )
    return parsed


async def list_industries(db: AsyncSession) -> list[dict]:
    return [{"name": name} for name in CLIENT_INDUSTRY_NAMES]


async def _assert_unique_active_name(
    db: AsyncSession, name: str, *, exclude_id: uuid.UUID | None = None
) -> None:
    stmt = select(Client.id).where(func.lower(Client.client_name) == name.lower(), Client.status == "ACTIVE")
    if exclude_id is not None:
        stmt = stmt.where(Client.id != exclude_id)
    if (await db.execute(stmt.limit(1))).scalar_one_or_none() is not None:
        raise HTTPException(status_code=409, detail=CLIENT_NAME_TAKEN)


