async def _set_status(db: AsyncSession, actor: dict | None, client_id: uuid.UUID, next_status: str) -> dict:
    customer = await _reload_client(db, client_id)
    if customer is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Client not found")
    if customer.status != next_status:
        if next_status == "ACTIVE":
            await _assert_unique_active_name(db, customer.client_name, exclude_id=client_id)
        customer.status = next_status
        try:
            await db.flush()
        except DBAPIError as exc:
            raise _db_error_to_http(exc) from exc
        await write_log(
            db,
            action="deactivated" if next_status == "INACTIVE" else "reactivated",
            entity_type="client", entity_id=customer.id, actor_employee_id=_actor_id(actor),
            details={"status": {"old": "ACTIVE" if next_status == "INACTIVE" else "INACTIVE", "new": next_status}},
        )
    return await get_client(db, client_id)


