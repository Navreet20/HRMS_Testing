async def _client_dicts(db: AsyncSession, clients: list[Client]) -> list[dict]:
    """Bulk-load locations and owner names, then serialize."""
    if not clients:
        return []
    ids = [c.id for c in clients]
    loc_rows = (
        await db.execute(
            select(ClientLocation).where(ClientLocation.client_id.in_(ids)).order_by(ClientLocation.id)
        )
    ).scalars().all()
    office_ids = {r.office_location_id for r in loc_rows if r.office_location_id is not None}
    offices = {}
    if office_ids:
        offices = {
            o.id: o
            for o in (await db.execute(select(Location).where(Location.id.in_(office_ids)))).scalars().all()
        }
    owner_ids = {c.account_owner for c in clients if c.account_owner is not None}
    owners: dict[uuid.UUID, str] = {}
    if owner_ids:
        for oid, first, last in (
            await db.execute(
                select(Employee.id, Employee.first_name, Employee.last_name).where(Employee.id.in_(owner_ids))
            )
        ).all():
            owners[oid] = f"{first or ''} {last or ''}".strip()
    out = []
    for c in clients:
        out.append(
            client_to_dict(
                c,
                locations=[r for r in loc_rows if r.client_id == c.id],
                offices=offices,
                stakeholders=[],
                owner_name=owners.get(c.account_owner),
            )
        )
    return out


async def _reload_client(db: AsyncSession, client_id: uuid.UUID) -> Client | None:
    return (await db.execute(select(Client).where(Client.id == client_id))).scalar_one_or_none()


async def _client_name_for_id(db: AsyncSession, client_id: uuid.UUID | str) -> str | None:
    try:
        cid = uuid.UUID(str(client_id))
    except ValueError:
        return None
    customer = await _reload_client(db, cid)
    return customer.client_name if customer else None


async def list_clients(db: AsyncSession) -> list[dict]:
    rows = (await db.execute(select(Client).order_by(func.lower(Client.client_name)))).scalars().all()
    return await _client_dicts(db, list(rows))


OVERVIEW_MAX_PAGE_SIZE = 100
_OVERVIEW_SORTS = ("name", "status")


def _project_counts_subquery() -> Any:
    closed = Project.status == "CLOSED"
    on_hold = Project.status == "ON_HOLD"
    return (
        select(
            Project.client_id.label("client_id"),
            func.count().label("total"),
            func.count().filter(~closed & ~on_hold).label("active"),
            func.count().filter(~closed).label("open"),
        )
        .group_by(Project.client_id)
        .subquery()
    )


def _overview_filters(*, q: str | None, status_filter: str | None, industry: str | None) -> list[Any]:
    clauses: list[Any] = []
    needle = (q or "").strip()
    if needle:
        pattern = f"%{needle}%"
        clauses.append(Client.client_name.ilike(pattern) | Client.client_code.ilike(pattern))
    stored_status = client_status_from_api(status_filter)
    if stored_status:
        clauses.append(Client.status == stored_status)
    wanted_industry = (industry or "").strip()
    if wanted_industry:
        clauses.append(Client.industry == wanted_industry)
    return clauses


async def clients_overview(
    db: AsyncSession,
    *,
    q: str | None = None,
    status_filter: str | None = None,
    industry: str | None = None,
    sort: str = "name",
    sort_dir: str = "asc",
    page: int = 1,
    page_size: int = 20,
) -> dict:
    """One page of the Clients directory with project counts joined in."""
    if sort not in _OVERVIEW_SORTS:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"sort must be one of: {', '.join(_OVERVIEW_SORTS)}",
        )
    page_size = max(1, min(page_size, OVERVIEW_MAX_PAGE_SIZE))
    filters = _overview_filters(q=q, status_filter=status_filter, industry=industry)
    total = int((await db.execute(select(func.count()).select_from(Client).where(*filters))).scalar_one())
    page_count = max(1, -(-total // page_size))
    page = min(max(1, page), page_count)
    counts = _project_counts_subquery()
    order_column = Client.status if sort == "status" else func.lower(Client.client_name)
    ordered = order_column.desc() if sort_dir == "desc" else order_column.asc()
    result = await db.execute(
        select(
            Client,
            func.coalesce(counts.c.total, 0),
            func.coalesce(counts.c.active, 0),
            func.coalesce(counts.c.open, 0),
        )
        .outerjoin(counts, counts.c.client_id == Client.id)
        .where(*filters)
        .order_by(ordered, func.lower(Client.client_name), Client.id)
        .offset((page - 1) * page_size)
        .limit(page_size)
    )
    rows = result.all()
    dicts = await _client_dicts(db, [r[0] for r in rows])
    items = []
    for row_dict, (_, project_count, active_count, open_count) in zip(dicts, rows):
        row_dict["projectCount"] = int(project_count)
        row_dict["activeProjectCount"] = int(active_count)
        row_dict["openProjectCount"] = int(open_count)
        items.append(row_dict)
    return {"items": items, "total": total, "page": page, "pageSize": page_size, "pageCount": page_count}


