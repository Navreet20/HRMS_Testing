CLIENT_CATEGORY_INTERMEDIARY = "intermediary"
CLIENT_CATEGORIES = (CLIENT_CATEGORY_INTERNAL, CLIENT_CATEGORY_DIRECT, CLIENT_CATEGORY_INTERMEDIARY)
