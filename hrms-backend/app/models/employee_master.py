# Shared checks, so the same rule reads the same everywhere. E.164: '+', country code, up to 15 digits in all.
PHONE_PATTERN = r"'^\+[1-9][0-9]{6,14}$'"
COUNTRY_PATTERN = "'^[A-Z]{2}$'"

# One company-wide running number for emp_id. Gaps (from a rolled-back save) are fine.
employee_number_seq = Sequence("employee_number_seq", metadata=Base.metadata)


