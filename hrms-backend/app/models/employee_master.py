class EmployeeAccessGrant(Base):
    """One grant of a module (or one submodule of it) to an employee. Rows are never updated except to revoke:
    a change of access level revokes the live row and inserts a new one in the same transaction. The revoked rows
    are the history. Every grant change is also written to activity_log."""
    __tablename__ = "employee_access_grants"
    __table_args__ = (
        # Skipped when submodule_id is NULL (a grant on the whole module). Otherwise the submodule must belong to
        # the granted module.
        ForeignKeyConstraint(
            ["module_id", "submodule_id"], ["submodules.module_id", "submodules.id"],
            name="fk_employee_access_grants_submodule_in_module"),
        CheckConstraint("access_level IN ('View', 'Edit', 'Manage')", name="ck_employee_access_grants_level"),
        # A revoke records who and when, together; and it cannot come before the grant.
        CheckConstraint(
            "(revoked_at IS NULL) = (revoked_by_employee_id IS NULL) "
            "AND (revoked_at IS NULL OR revoked_at >= granted_at)",
            name="ck_employee_access_grants_revoked"),
        # The database itself refuses a second live grant for the same scope. Leads with employee_id, so it also
        # serves "what can this employee access" at sign-in.
        Index("uq_employee_access_grants_one_active", "employee_id", "module_id", text("coalesce(submodule_id, 0)"),
              unique=True, postgresql_where=text("revoked_at IS NULL")),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    employee_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("employees.id", name="fk_employee_access_grants_employee_id"))
    module_id: Mapped[int] = mapped_column(ForeignKey("modules.id", name="fk_employee_access_grants_module_id"))
    submodule_id: Mapped[int | None] = mapped_column(SmallInteger)
    access_level: Mapped[str] = mapped_column(String(12))
    granted_by_employee_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("employees.id", name="fk_employee_access_grants_granted_by_employee_id"))
    granted_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), server_default=text("now()"))
    revoked_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_by_employee_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("employees.id", name="fk_employee_access_grants_revoked_by_employee_id"))
