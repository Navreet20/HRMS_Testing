# Two rules that must always hold for an employee: emp_id comes only from employee_number_seq and never changes (it is
# printed on badges and payslips; a value typed by hand could later collide with the sequence), and
# only a Draft (never finished, never used) can be deleted; everyone else is marked Inactive. One statement each:
# installed by create_all (after_create below) and again, harmlessly, by schema_ensure.
EMPLOYEE_GUARD_SQL = (
    """CREATE OR REPLACE FUNCTION employees_guard() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.emp_id IS NOT NULL THEN
            RAISE EXCEPTION USING MESSAGE = 'emp_id is generated by the database and cannot be supplied',
                                  ERRCODE = '23514';
        END IF;
        NEW.emp_id := 'EMP-' || lpad(nextval('employee_number_seq')::text, 5, '0');
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'Draft' THEN
            RETURN OLD;
        END IF;
        RAISE EXCEPTION USING MESSAGE = 'employees are never deleted: mark the employee Inactive instead', ERRCODE = '23001';
    END IF;
    IF NEW.emp_id IS DISTINCT FROM OLD.emp_id THEN
        RAISE EXCEPTION USING MESSAGE = 'emp_id cannot be changed once the employee is created', ERRCODE = '23001';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql""",
    "DROP TRIGGER IF EXISTS trg_employees_guard ON employees",
    """CREATE TRIGGER trg_employees_guard BEFORE INSERT OR UPDATE OF emp_id OR DELETE ON employees
    FOR EACH ROW EXECUTE FUNCTION employees_guard()""",
)

# Stops a reporting line from forming a loop, the same way departments_block_loop does: walk up from the chosen
# manager; if the walk reaches the employee, refuse. The advisory lock makes manager changes run one at a time, so
# two changes that are each fine alone cannot make a loop together. Being one's own manager is left to
# ck_employees_not_own_manager.
EMPLOYEE_MANAGER_LOOP_SQL = (
    """CREATE OR REPLACE FUNCTION employees_block_manager_loop() RETURNS trigger AS $$
BEGIN
    IF NEW.reporting_manager_id IS NULL OR NEW.reporting_manager_id = NEW.id THEN
        RETURN NEW;
    END IF;
    PERFORM pg_advisory_xact_lock(8204119);
    IF EXISTS (
        WITH RECURSIVE up(id, manager) AS (
            SELECT id, reporting_manager_id FROM employees WHERE id = NEW.reporting_manager_id
            UNION
            SELECT e.id, e.reporting_manager_id FROM employees e JOIN up ON e.id = up.manager
        )
        SELECT 1 FROM up WHERE id = NEW.id
    ) THEN
        RAISE EXCEPTION USING MESSAGE = 'an employee cannot report to themselves or to someone in their own reporting line',
                              ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql""",
    "DROP TRIGGER IF EXISTS trg_employees_no_manager_loop ON employees",
    """CREATE TRIGGER trg_employees_no_manager_loop BEFORE INSERT OR UPDATE OF reporting_manager_id ON employees
    FOR EACH ROW EXECUTE FUNCTION employees_block_manager_loop()""",
)


class Employee(Base):
    """One person. Starts as Draft (only the name is required, so HR can save a half-filled form); every other
    status needs the job fields (ck_employees_complete_unless_draft). Pending = joining date still in the future;
    the service sets it and moves it to Active on that date (a CHECK cannot compare with today). Never deleted once
    past Draft, and emp_id is set from the sequence on insert and never changes: all enforced by trg_employees_guard.

    The national ID number is stored only encrypted (by the service); national_id_last4 is what screens show.
    Never write either one, date_of_birth or ethnicity to the activity log."""
    __tablename__ = "employees"
    __table_args__ = (
        # --- identity
        UniqueConstraint("emp_id", name="uq_employees_emp_id"),
        UniqueConstraint("employee_code", name="uq_employees_employee_code"),
        CheckConstraint("status IN ('Draft', 'New', 'Pending', 'Active', 'Inactive')", name="ck_employees_status"),
        CheckConstraint(
            "status = 'Draft' OR (official_email IS NOT NULL AND department_id IS NOT NULL "
            "AND designation_id IS NOT NULL AND location_id IS NOT NULL AND employment_type IS NOT NULL "
            "AND work_mode IS NOT NULL AND date_of_joining IS NOT NULL AND role IS NOT NULL)",
            name="ck_employees_complete_unless_draft"),
        # --- contact
        # Sign-in and "find by email", ignoring capital letters.
        Index("uq_employees_official_email", func.lower(text("official_email")), unique=True),
        CheckConstraint(f"phone_number ~ {PHONE_PATTERN}", name="ck_employees_phone"),
        CheckConstraint(f"alternate_phone_number ~ {PHONE_PATTERN}", name="ck_employees_alternate_phone"),
        # --- job
        CheckConstraint("work_mode IN ('Onsite', 'Remote', 'Hybrid')", name="ck_employees_work_mode"),
        CheckConstraint(
            "employment_type IN ('Full-time', 'Part-time', 'Contract', 'Intern')", name="ck_employees_employment_type"),
        CheckConstraint("role IN ('Employee', 'Manager', 'HR', 'Admin')", name="ck_employees_role"),
        CheckConstraint("reporting_manager_id <> id", name="ck_employees_not_own_manager"),
        CheckConstraint(
            "(payroll_start_date IS NULL OR date_of_joining IS NULL OR payroll_start_date >= date_of_joining) "
            "AND (date_of_birth IS NULL OR date_of_joining IS NULL OR date_of_birth < date_of_joining)",
            name="ck_employees_dates"),
        # "Can this department / location / designation be deactivated?" and "employees on this policy".
        Index("ix_employees_department", "department_id"),
        Index("ix_employees_location", "location_id"),
        Index("ix_employees_designation", "designation_id"),
        Index("ix_employees_leave_policy", "leave_policy_id"),
        # "My team": the direct reports of a manager.
        Index("ix_employees_reporting_manager", "reporting_manager_id"),
        # --- personal
        CheckConstraint(
            "gender IN ('Male', 'Female', 'Non-binary', 'Prefer not to say')", name="ck_employees_gender"),
        CheckConstraint(
            "marital_status IN ('Single', 'Married', 'Divorced', 'Widowed', 'Separated')",
            name="ck_employees_marital_status"),
        CheckConstraint(f"nationality_code ~ {COUNTRY_PATTERN}", name="ck_employees_nationality_code"),
        # --- national ID: the type, the encrypted number and the last 4 are saved together or not at all.
        CheckConstraint(
            "(national_id_document_type_id IS NULL AND national_id_number_encrypted IS NULL "
            "AND national_id_last4 IS NULL) "
            "OR (national_id_document_type_id IS NOT NULL AND national_id_number_encrypted IS NOT NULL "
            "AND national_id_last4 IS NOT NULL)",
            name="ck_employees_national_id_together"),
        CheckConstraint("national_id_last4 ~ '^[0-9A-Za-z]{4}$'", name="ck_employees_national_id_last4"),
    )

    # --- identity
    id: Mapped[uuid.UUID] = uuid_pk()
    # Set by trg_employees_guard on insert: 'EMP-' + next employee_number_seq value padded to 5 digits. A value sent
    # by the caller is refused.
    emp_id: Mapped[str] = mapped_column(String(10), server_default=FetchedValue())
    employee_code: Mapped[str | None] = mapped_column(String(20))
    first_name: Mapped[str] = mapped_column(String(100))
    middle_name: Mapped[str | None] = mapped_column(String(100))
    last_name: Mapped[str] = mapped_column(String(100))
    status: Mapped[str] = mapped_column(
        CodeMap(10, EMPLOYEE_STATUS_TO_DB, EMPLOYEE_STATUS_FROM_DB), server_default=text("'Draft'"))
    # --- contact
    personal_email: Mapped[str | None] = mapped_column(String(255))
    official_email: Mapped[str | None] = mapped_column(String(255))
    phone_number: Mapped[str | None] = mapped_column(String(16))
    alternate_phone_number: Mapped[str | None] = mapped_column(String(16))
    # --- job
    work_mode: Mapped[str | None] = mapped_column(CodeMap(10, WORK_MODE_TO_DB, WORK_MODE_FROM_DB))
    department_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("departments.id", name="fk_employees_department_id"))
    location_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("locations.id", name="fk_employees_location_id"))
    designation_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("designations.id", name="fk_employees_designation_id"))
    employment_type: Mapped[str | None] = mapped_column(
        CodeMap(20, EMPLOYMENT_TYPE_TO_DB, EMPLOYMENT_TYPE_FROM_DB))
    reporting_manager_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("employees.id", name="fk_employees_reporting_manager_id"))
    date_of_joining: Mapped[dt.date | None] = mapped_column(Date)
    payroll_start_date: Mapped[dt.date | None] = mapped_column(Date)
    leave_policy_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("leave_policies.id", name="fk_employees_leave_policy_id"))
    timesheet_required: Mapped[bool] = mapped_column(Boolean, server_default=text("true"))
    role: Mapped[str | None] = mapped_column(CodeMap(16, EMPLOYEE_ROLE_TO_DB, EMPLOYEE_ROLE_FROM_DB))
    # --- personal (ethnicity has no fixed list here: the allowed answers differ by country)
    date_of_birth: Mapped[dt.date | None] = mapped_column(Date)
    nationality_code: Mapped[str | None] = mapped_column(CHAR(2))
    gender: Mapped[str | None] = mapped_column(String(20))
    marital_status: Mapped[str | None] = mapped_column(String(10))
    ethnicity: Mapped[str | None] = mapped_column(String(30))
    # --- national ID
    national_id_document_type_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("national_id_document_types.id", name="fk_employees_national_id_document_type_id"))
    national_id_number_encrypted: Mapped[str | None] = mapped_column(Text)
    national_id_last4: Mapped[str | None] = mapped_column(CHAR(4))
    # --- app-level extras the portal screens read (all optional). Existing databases get them from schema_ensure.
    is_system_account: Mapped[bool | None] = mapped_column(Boolean, server_default=text("false"), default=False)
    theme_preference: Mapped[str | None] = mapped_column(String(16))
    quick_actions_preference: Mapped[str | None] = mapped_column(String(512))
    avatar_object_key: Mapped[str | None] = mapped_column(String(500))
    company_name: Mapped[str | None] = mapped_column(String(200))
    department_label: Mapped[str | None] = mapped_column(String(150))
    # Microsoft Entra object id (oid). Set on first successful Entra sign-in; no separate auth table.
    # Uniqueness (when set) is the partial index uq_employees_entra_oid created in app/db/schema_ensure.py.
    entra_oid: Mapped[str | None] = mapped_column(String(128))

    # --- legacy attribute names, so older service code keeps working (queries and attribute access both)
    employee_id = synonym("id")
    email_id = synonym("official_email")
    employment_start_date = synonym("date_of_joining")
    business_employee_id = synonym("emp_id")
    nationality = synonym("nationality_code")
    company = synonym("company_name")
    department = synonym("department_label")


for _statement in EMPLOYEE_GUARD_SQL + EMPLOYEE_MANAGER_LOOP_SQL:
    event.listen(Employee.__table__, "after_create", DDL(_statement))


