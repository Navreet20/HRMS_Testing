"""Employee Master and RBAC: employees, national ID document types, addresses, emergency contacts, onboarding
packet documents, skills, employee skills, and the access tables (modules, submodules, employee access grants).

Rules the database cannot hold (a manager or department head must be Active, no grant to an Inactive employee or
on an inactive module, the national ID number checked against number_format and encrypted before it is saved,
Pending while the joining date is in the future, then Active on the joining date in the company's time zone) are
enforced in the service layer.
Grant changes are not audited here: they go to activity_log (entity_type 'employee', actions access_granted,
access_changed, access_revoked) in the same transaction as the grant insert or revoke."""
